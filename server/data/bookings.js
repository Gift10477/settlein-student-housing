const safeLog = require('../safeLog');
const { requireUser, requireOwner } = require('../middleware/session');
const { allowFields } = require('../middleware/fields');
const express = require('express');
const router = express.Router();
const db = require('../db');
const { PAYMENT_WINDOW_HOURS, bookingFee, paymentFields, recordPayment } = require('../services/bookingPayments');
const {bookingSelect}=require('../services/bookingQuery');

function badRequest(res, message) {
  return res.status(400).json({ error: 'Bad Request', message, status_code: 400 });
}

function isNonEmptyString(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

const {validDate}=require('../services/validation');

function publicBooking(row) {
  return paymentFields(Object.fromEntries(['id', 'user_id', 'student_id', 'property_id', 'property_title', 'status', 'move_in_date', 'expected_arrival_time', 'lease_start_date', 'lease_end_date', 'relocation_window_start', 'relocation_window_end', 'lease_duration', 'notes', 'created_at', 'booking_fee', 'payment_status', 'payment_deadline', 'paid_at', 'payment_reference', 'payment_method'].map((field) => [field, row[field]])));
}

router.post('/:id/mock-payment', requireUser, recordPayment());

// 1. GET all bookings
router.get('/', requireUser, async (req, res) => {
  try {
    const [rows] = await db.query(bookingSelect+' WHERE user_id = ? ORDER BY id DESC', [req.userId]);
    res.json(rows.map(publicBooking));
  } catch (err) {
    safeLog('Database operation failed');
    res.status(500).json({ error: 'Failed to fetch bookings from database' });
  }
});

// 2. GET bookings by user ID
router.get('/user/:userId', requireOwner((req) => req.params.userId), async (req, res) => {
  try {
    const [rows] = await db.query(bookingSelect+' WHERE user_id = ? ORDER BY id DESC', [req.params.userId]);
    res.json(rows.map(publicBooking));
  } catch (err) {
    safeLog('Database operation failed');
    res.status(500).json({ error: 'Failed to fetch user bookings' });
  }
});

// 3. POST new booking (Real-time direct booking)
router.post('/', requireOwner((req) => req.body?.user_id), allowFields(['user_id', 'student_id', 'property_id', 'property_title', 'move_in_date', 'expected_arrival_time', 'lease_duration', 'notes']), async (req, res) => {
  let connection;
  try {
    if (!req.body || typeof req.body !== 'object' || Array.isArray(req.body)) {
      return badRequest(res, 'Request body must be a JSON object.');
    }
    const {
      user_id,
      student_id,
      property_id,
      property_title,
      move_in_date,
      expected_arrival_time,
      lease_duration = '1 Semester (4 months)',
      notes
    } = req.body;
    if (String(property_id || '').length>50 || String(student_id || '').length>100 || String(notes || '').length>5000) return badRequest(res,'One or more reservation fields are too long.');
    if (!['1 Semester (4 months)','2 Semesters (8 months)','1 Full Academic Year (12 months)'].includes(lease_duration)) return badRequest(res,'Choose one of the available lease durations.');
    if (expected_arrival_time && !['08:00 AM','10:00 AM','12:00 PM','02:00 PM','04:00 PM','06:00 PM'].includes(expected_arrival_time)) return badRequest(res,'Choose an available arrival time.');

    if (!Number.isInteger(user_id) || user_id < 1) {
      return badRequest(res, "Field 'user_id' must be a positive integer.");
    }
    if (!isNonEmptyString(property_id)) {
      return badRequest(res, "Field 'property_id' is required and must be a non-empty string.");
    }
    if (student_id !== undefined && !isNonEmptyString(student_id)) {
      return badRequest(res, "Field 'student_id' must be a non-empty string when provided.");
    }
    if (property_title !== undefined && !isNonEmptyString(property_title)) {
      return badRequest(res, "Field 'property_title' must be a non-empty string when provided.");
    }
    if (move_in_date !== undefined && !validDate(move_in_date)) {
      return badRequest(res, "Field 'move_in_date' must be a valid date.");
    }
    if (expected_arrival_time !== undefined && !isNonEmptyString(expected_arrival_time)) {
      return badRequest(res, "Field 'expected_arrival_time' must be a non-empty string when provided.");
    }
    if (lease_duration !== undefined && !isNonEmptyString(lease_duration)) {
      return badRequest(res, "Field 'lease_duration' must be a non-empty string.");
    }
    if (notes !== undefined && typeof notes !== 'string') {
      return badRequest(res, "Field 'notes' must be a string when provided.");
    }
    if (req.body.status !== undefined || req.body.lease_start_date !== undefined ||
        req.body.lease_end_date !== undefined || req.body.relocation_window_start !== undefined ||
        req.body.relocation_window_end !== undefined) {
      return badRequest(res, 'Lease dates and status are generated by the booking service and cannot be supplied.');
    }

    const [properties] = await db.query('SELECT * FROM properties WHERE id = ? AND verified = 1 AND vacant_units > 0', [property_id]);
    if (!properties.length) return res.status(409).json({ error: 'This property is unavailable.' });
    if (!move_in_date || !validDate(move_in_date) || move_in_date.slice(0, 10) < new Date().toISOString().slice(0, 10)) return badRequest(res, 'Choose a current or future move-in date.');
    const arrivalDate = move_in_date ? new Date(move_in_date) : new Date();
    const arrivalTime = expected_arrival_time || '10:00 AM';
    const moveInIso = arrivalDate.toISOString();
    const leaseStartDate = arrivalDate.toISOString().split('T')[0];

    // Calculate lease end date based on duration
    const endDate = new Date(arrivalDate);
    if (lease_duration.includes('1 Semester') || lease_duration.includes('4')) {
      endDate.setMonth(endDate.getMonth() + 4);
    } else if (lease_duration.includes('2 Semester') || lease_duration.includes('8')) {
      endDate.setMonth(endDate.getMonth() + 8);
    } else if (lease_duration.includes('Year') || lease_duration.includes('12')) {
      endDate.setFullYear(endDate.getFullYear() + 1);
    } else {
      endDate.setMonth(endDate.getMonth() + 4);
    }
    const leaseEndDate = endDate.toISOString().split('T')[0];

    // Relocation window (1 day before to 2 days after move-in)
    const relocStart = new Date(arrivalDate);
    relocStart.setDate(relocStart.getDate() - 1);
    const relocEnd = new Date(arrivalDate);
    relocEnd.setDate(relocEnd.getDate() + 2);

    const now = new Date();
    const fee = bookingFee(properties[0]);
    const deadline = new Date(now.getTime() + PAYMENT_WINDOW_HOURS * 3600000).toISOString();

    const sql = `
      INSERT INTO bookings (
        user_id, student_id, property_id, property_title, status, move_in_date,
        expected_arrival_time, lease_start_date, lease_end_date,
        relocation_window_start, relocation_window_end, lease_duration, notes, created_at,
        booking_fee, payment_required, payment_deadline
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `;

    const values = [
      Number(user_id),
      student_id || '',
      String(property_id),
      properties[0].title,
      'pending',
      moveInIso,
      arrivalTime,
      leaseStartDate,
      leaseEndDate,
      relocStart.toISOString(),
      relocEnd.toISOString(),
      lease_duration,
      notes || '',
      now, fee, 1, deadline
    ];

    connection = await db.getConnection();
    await connection.beginTransaction();
    const [result] = await connection.query(sql, values);
    await connection.query('INSERT INTO audit_logs (actor_id, action, target_id) VALUES (?, ?, ?)', [req.userId, 'reservation.created', String(result.insertId)]);
    await connection.commit();

    res.status(201).json({
      status_code: 201,
      message: 'Reservation submitted. Pay the booking fee within 24 hours before administrator approval.',
      booking_id: result.insertId,
      booking: {
        booking_id: result.insertId,
        user_id: Number(user_id),
        student_id: student_id || '',
        property_id: String(property_id),
        accommodation_name: properties[0].title,
        status: 'pending',
        booking_fee: fee,
        payment_status: 'unpaid',
        payment_deadline: deadline,
        move_in_date: moveInIso,
        expected_arrival_time: arrivalTime,
        lease_start_date: leaseStartDate,
        lease_end_date: leaseEndDate,
        relocation_window_start: relocStart.toISOString(),
        relocation_window_end: relocEnd.toISOString(),
        booked_at: now.toISOString()
      }
    });
  } catch (err) {
    if (connection) await connection.rollback();
    safeLog('Database operation failed');
    res.status(500).json({ error: 'Failed to create booking in database', status_code: 500 });
  } finally { if (connection) connection.release(); }
});

module.exports = router;
